//! Per-profile fingerprint overrides, applied in the page.
//!
//! The script built here is registered over the Chrome DevTools Protocol
//! (`browser::cdp`) as an init script, so it runs in every frame before any
//! site script. Viewport, user agent and timezone are applied the same way.
//! Language also goes through a flag (see `launcher::build_args`) so the
//! network layer and the JS layer agree.
//!
//! Limitation: this is best-effort identity shaping, not undetectable. TLS
//! fingerprints, font metrics and the raw WebGL parameter set still come from
//! the host.

use crate::error::AppResult;
use crate::models::profile::{Fingerprint, Geolocation};
use serde_json::json;

/// Builds the init script for `fp` with the per-profile seed that drives
/// canvas noise. Every value is embedded as a JSON literal, so user input can
/// never break out of the script.
pub fn script_with_seed(fp: &Fingerprint, seed: u32) -> AppResult<String> {
    script_with_phone_dpr(fp, seed, None)
}

/// Same as [`script_with_seed`], plus the device pixel ratio a phone preset
/// should report. The engine's value carries the host's fractional display
/// scale (`2.9999999`), which is not a density bucket a real phone reports, so
/// the page gets the clean value instead.
pub fn script_with_phone_dpr(
    fp: &Fingerprint,
    seed: u32,
    phone_dpr: Option<f64>,
) -> AppResult<String> {
    let mut parts: Vec<String> = Vec::new();

    parts.push(canvas_patch(seed));
    if let Some(ua) = &fp.user_agent {
        parts.push(client_identity_patch(ua)?);
    }

    if let Some(lang) = &fp.language {
        let langs = json!([lang]);
        parts.push(format!(
            "define(Navigator.prototype, 'language', {lang});\n\
             define(Navigator.prototype, 'languages', {langs});",
            lang = serde_json::to_string(lang)?,
            langs = langs,
        ));
    }
    if let Some(platform) = &fp.platform {
        parts.push(format!(
            "define(Navigator.prototype, 'platform', {});",
            serde_json::to_string(platform)?
        ));
    }
    if let Some(tz) = &fp.timezone {
        parts.push(timezone_patch(tz)?);
    }
    if let Some(geo) = &fp.geolocation {
        parts.push(geolocation_patch(geo)?);
    }
    if let Some(fonts) = &fp.fonts {
        parts.push(font_patch(fonts)?);
    }
    if let Some(screen) = &fp.screen {
        parts.push(screen_patch(screen.width, screen.height));
    }
    if let Some(dpr) = phone_dpr {
        parts.push(format!(
            // `devicePixelRatio` is an own accessor on the global object, so
            // defining it on `Window.prototype` would be shadowed.
            "define(window, 'devicePixelRatio', {});",
            serde_json::to_string(&dpr)?
        ));
    }
    if fp.disable_webrtc {
        parts.push(webrtc_patch());
    }

    Ok(format!(
        "// AUTO-GENERATED by Multi Browser Manager. Do not edit.\n\
         (() => {{\n\
         'use strict';\n\
         const define = (target, prop, value) => {{\n\
           Object.defineProperty(target, prop, {{ get: () => value, configurable: true }});\n\
         }};\n\
         {}\n\
         }})();\n",
        parts.join("\n")
    ))
}

/// Stable per-profile seed (FNV-1a), so canvas noise is the same on every launch
/// of one profile but differs between profiles.
pub fn profile_seed(profile_id: &str) -> u32 {
    profile_id
        .bytes()
        .fold(0x811c_9dc5u32, |h, b| (h ^ b as u32).wrapping_mul(0x0100_0193))
}

/// Flips the low bit of a sparse set of RGB values, seeded per profile. Enough
/// to change canvas hashes; invisible to the eye.
fn canvas_patch(seed: u32) -> String {
    format!(
        "const NOISE_SEED = {seed};\n\
         const noiseAt = (i) => {{ let x = (NOISE_SEED ^ Math.imul(i, 2654435761)) >>> 0; x ^= x << 13; x ^= x >>> 17; x ^= x << 5; return x >>> 0; }};\n\
         const origGetImageData = CanvasRenderingContext2D.prototype.getImageData;\n\
         const noisify = (img) => {{ const d = img.data; for (let p = 0; p < d.length / 4; p += 61) {{ for (let c = 0; c < 3; c++) {{ const k = p * 4 + c; d[k] ^= noiseAt(k) & 1; }} }} return img; }};\n\
         const noisyCopy = (canvas) => {{\n\
           if (!canvas.width || !canvas.height) return canvas;\n\
           const c = document.createElement('canvas');\n\
           c.width = canvas.width;\n\
           c.height = canvas.height;\n\
           const ctx = c.getContext('2d');\n\
           ctx.drawImage(canvas, 0, 0);\n\
           ctx.putImageData(noisify(origGetImageData.call(ctx, 0, 0, c.width, c.height)), 0, 0);\n\
           return c;\n\
         }};\n\
         CanvasRenderingContext2D.prototype.getImageData = function (...args) {{ return noisify(origGetImageData.apply(this, args)); }};\n\
         const origToDataURL = HTMLCanvasElement.prototype.toDataURL;\n\
         HTMLCanvasElement.prototype.toDataURL = function (...args) {{ return origToDataURL.apply(noisyCopy(this), args); }};\n\
         const origToBlob = HTMLCanvasElement.prototype.toBlob;\n\
         HTMLCanvasElement.prototype.toBlob = function (...args) {{ return origToBlob.apply(noisyCopy(this), args); }};"
    )
}

/// Client-identity patch derived from the chosen user agent: navigator.platform,
/// maxTouchPoints and navigator.userAgentData (brands, mobile, platform and
/// high-entropy values), so JS-side checks agree with the UA header. Android
/// UAs also get phone-consistent hardware values (cores, memory, PDF viewer,
/// TTS voices) and the device's GPU strings for the unmasked WebGL values.
fn client_identity_patch(ua: &str) -> AppResult<String> {
    let id = UaIdentity::from_ua(ua);
    let touch = if id.mobile { 5 } else { 0 };
    let data = json!({
        "brands": [
            { "brand": "Chromium", "version": id.major },
            { "brand": "Google Chrome", "version": id.major },
            { "brand": "Not.A/Brand", "version": "8" }
        ],
        "fullVersions": [
            { "brand": "Chromium", "version": id.full_version },
            { "brand": "Google Chrome", "version": id.full_version },
            { "brand": "Not.A/Brand", "version": "8.0.0.0" }
        ],
        "mobile": id.mobile,
        "platform": id.ua_platform,
        "navPlatform": id.nav_platform,
        "platformVersion": id.platform_version,
        "architecture": id.architecture,
        "model": id.model,
        "uaFullVersion": id.full_version,
        "formFactors": if id.mobile { ["Mobile"] } else { ["Desktop"] },
        "touchPoints": touch,
    });
    let mut script = format!(
        "const UA_DATA = {data};\n\
         define(Navigator.prototype, 'platform', UA_DATA.navPlatform);\n\
         define(Navigator.prototype, 'maxTouchPoints', UA_DATA.touchPoints);\n\
         const uaHighEntropy = () => ({{\n\
           brands: UA_DATA.brands, mobile: UA_DATA.mobile, platform: UA_DATA.platform,\n\
           platformVersion: UA_DATA.platformVersion, architecture: UA_DATA.architecture,\n\
           bitness: '64', model: UA_DATA.model, uaFullVersion: UA_DATA.uaFullVersion,\n\
           fullVersionList: UA_DATA.fullVersions, formFactors: UA_DATA.formFactors, wow64: false,\n\
         }});\n\
         define(Navigator.prototype, 'userAgentData', {{\n\
           brands: UA_DATA.brands,\n\
           mobile: UA_DATA.mobile,\n\
           platform: UA_DATA.platform,\n\
           getHighEntropyValues(hints) {{\n\
             const all = uaHighEntropy();\n\
             const out = {{}};\n\
             for (const h of ['brands', 'mobile', 'platform', ...hints]) if (h in all) out[h] = all[h];\n\
             return Promise.resolve(out);\n\
           }},\n\
           toJSON() {{ return {{ brands: this.brands, mobile: this.mobile, platform: this.platform }}; }},\n\
         }});",
        data = data,
    );
    if id.mobile {
        script.push_str(&mobile_device_patch(ua.contains("; wv)")));
        if let Some((vendor, renderer)) = crate::browser::user_agent::phone_gpu_for_ua(ua) {
            script.push_str(&webgl_gpu_patch(vendor, renderer)?);
        }
    }
    Ok(script)
}

/// Desktop-Chrome hardware values that contradict a phone UA: core count,
/// memory bucket, the fixed PDF-viewer plugin list (Android has no inline PDF
/// viewer, so `plugins`/`mimeTypes` are empty and `pdfViewerEnabled` false),
/// the TTS voice list (always populated on Android) and — for Chrome-style
/// UAs, since WebView never ships it — Web Bluetooth.
fn mobile_device_patch(webview: bool) -> String {
    let mut js = "const emptyArrayLike = (Ctor) => {\n\
       const arr = Object.create(Ctor && Ctor.prototype ? Ctor.prototype : Object.prototype);\n\
       define(arr, 'length', 0);\n\
       define(arr, 'item', () => null);\n\
       define(arr, 'namedItem', () => null);\n\
       return arr;\n\
     };\n\
     define(Navigator.prototype, 'hardwareConcurrency', 8);\n\
     define(Navigator.prototype, 'deviceMemory', 8);\n\
     define(Navigator.prototype, 'plugins', emptyArrayLike(window.PluginArray));\n\
     define(Navigator.prototype, 'mimeTypes', emptyArrayLike(window.MimeTypeArray));\n\
     define(Navigator.prototype, 'pdfViewerEnabled', false);\n\
     if (window.speechSynthesis && window.SpeechSynthesisVoice) {\n\
       try {\n\
         const makeVoice = (v) => {\n\
           const voice = Object.create(window.SpeechSynthesisVoice.prototype);\n\
           for (const key of ['voiceURI', 'name', 'lang', 'localService', 'default']) define(voice, key, v[key]);\n\
           return voice;\n\
         };\n\
         const VOICES = [\n\
           { voiceURI: 'Google US English', name: 'Google US English', lang: 'en-US', localService: true, default: true },\n\
           { voiceURI: 'Google Bahasa Indonesia', name: 'Google Bahasa Indonesia', lang: 'id-ID', localService: true, default: false },\n\
         ].map(makeVoice);\n\
         define(window.speechSynthesis, 'getVoices', () => VOICES);\n\
       } catch (e) {}\n\
     }"
    .to_string();
    if !webview {
        js.push_str(bluetooth_patch());
    }
    js
}

/// Chrome for Android ships Web Bluetooth; Chromium on Linux has no
/// `navigator.bluetooth` at all, so a Chrome-style Android UA gets a minimal
/// stand-in with the shape feature probes look for.
fn bluetooth_patch() -> &'static str {
    "try {\n\
       if (!navigator.bluetooth) {\n\
         let bluetooth;\n\
         if (window.Bluetooth) {\n\
           try { bluetooth = new window.Bluetooth(); } catch (e) { bluetooth = Object.create(window.Bluetooth.prototype); }\n\
         } else {\n\
           const Bt = class Bluetooth extends EventTarget {};\n\
           bluetooth = new Bt();\n\
           define(window, 'Bluetooth', Bt);\n\
         }\n\
         define(bluetooth, 'getAvailability', () => Promise.resolve(true));\n\
         define(bluetooth, 'getDevices', () => Promise.resolve([]));\n\
         define(bluetooth, 'requestDevice', () => Promise.reject(new DOMException('User cancelled the request.', 'NotFoundError')));\n\
         define(Navigator.prototype, 'bluetooth', bluetooth);\n\
       }\n\
     } catch (e) {}"
}

/// Answers the unmasked WebGL vendor/renderer enums with the device's real GPU
/// instead of the host desktop's. The extension itself stays available, as on
/// Android Chrome; only the two parameters are replaced.
fn webgl_gpu_patch(vendor: &str, renderer: &str) -> AppResult<String> {
    Ok(format!(
        "const GPU = {{ vendor: {}, renderer: {} }};\n\
         for (const Ctor of [window.WebGLRenderingContext, window.WebGL2RenderingContext]) {{\n\
           if (!Ctor) continue;\n\
           const origGetParameter = Ctor.prototype.getParameter;\n\
           Ctor.prototype.getParameter = function (pname) {{\n\
             if (pname === 0x9245) return GPU.vendor;\n\
             if (pname === 0x9246) return GPU.renderer;\n\
             return origGetParameter.call(this, pname);\n\
           }};\n\
         }}",
        serde_json::to_string(vendor)?,
        serde_json::to_string(renderer)?,
    ))
}

/// What a given user agent claims to be, used for the Client Hints spoof.
pub struct UaIdentity {
    pub nav_platform: &'static str,
    pub ua_platform: &'static str,
    pub mobile: bool,
    pub architecture: &'static str,
    pub platform_version: String,
    pub model: String,
    pub major: String,
    pub full_version: String,
}

impl UaIdentity {
    pub fn from_ua(ua: &str) -> Self {
        let (nav_platform, ua_platform, mobile) = if ua.contains("Android") {
            ("Linux armv8l", "Android", true)
        } else if ua.contains("Windows") {
            ("Win32", "Windows", false)
        } else if ua.contains("Macintosh") {
            ("MacIntel", "macOS", false)
        } else {
            ("Linux x86_64", "Linux", false)
        };
        // Digits and dots directly after `marker`, e.g. "152.0.7977.87".
        let after = |marker: &str| -> String {
            ua.split(marker)
                .nth(1)
                .unwrap_or("")
                .chars()
                .take_while(|c| c.is_ascii_digit() || *c == '.')
                .collect()
        };
        let full_version = after("Chrome/");
        let major = full_version.split('.').next().unwrap_or("").to_string();
        Self {
            nav_platform,
            ua_platform,
            mobile,
            architecture: if mobile { "arm" } else { "x86" },
            platform_version: if mobile { after("Android ") } else { String::new() },
            model: if mobile { android_model(ua) } else { String::new() },
            major,
            full_version,
        }
    }
}

/// Device model from an Android UA: `Linux; Android 16; 23127PN0CG Build/...`.
fn android_model(ua: &str) -> String {
    let Some(rest) = ua.split("Android ").nth(1) else {
        return String::new();
    };
    let Some((_, after)) = rest.split_once("; ") else {
        return String::new();
    };
    let segment = after.split([';', ')']).next().unwrap_or("");
    segment.split(" Build/").next().unwrap_or("").trim().to_string()
}

fn timezone_patch(tz: &str) -> AppResult<String> {
    // Intl's resolved zone is what sites read; Date's offset follows the zone
    // only through the browser TZ, so we patch the formatter output too.
    Ok(format!(
        "const TZ = {tz};\n\
         const origResolved = Intl.DateTimeFormat.prototype.resolvedOptions;\n\
         Intl.DateTimeFormat.prototype.resolvedOptions = function () {{\n\
           const o = origResolved.call(this);\n\
           o.timeZone = TZ;\n\
           return o;\n\
         }};",
        tz = serde_json::to_string(tz)?
    ))
}

fn geolocation_patch(geo: &Geolocation) -> AppResult<String> {
    let pos = json!({
        "coords": {
            "latitude": geo.latitude,
            "longitude": geo.longitude,
            "accuracy": geo.accuracy,
            "altitude": null,
            "altitudeAccuracy": null,
            "heading": null,
            "speed": null,
        },
        "timestamp": 0,
    });
    Ok(format!(
        "const POS = {pos};\n\
         const fakeGeo = {{\n\
           getCurrentPosition(success) {{ success({{ ...POS, timestamp: Date.now() }}); }},\n\
           watchPosition(success) {{ success({{ ...POS, timestamp: Date.now() }}); return 0; }},\n\
           clearWatch() {{}},\n\
         }};\n\
         define(Navigator.prototype, 'geolocation', fakeGeo);",
        pos = pos
    ))
}

fn screen_patch(width: u32, height: u32) -> String {
    // Availability equals the full size: no taskbar/notch is modeled.
    format!(
        "const SCREEN = {{ width: {width}, height: {height} }};\n\
         for (const key of ['width', 'availWidth']) define(Screen.prototype, key, SCREEN.width);\n\
         for (const key of ['height', 'availHeight']) define(Screen.prototype, key, SCREEN.height);"
    )
}

/// Drops ICE servers and hides ICE candidates, so no local/public IP can be
/// read from WebRTC. Calls (video/voice) will not connect; that is the point.
fn webrtc_patch() -> String {
    // The page's own `onicecandidate` must stay silent too, or a site could
    // collect candidates before reading `localDescription`.
    r#"if (window.RTCPeerConnection) {
  const Orig = window.RTCPeerConnection;
  const strip = (sdp) => String(sdp).replace(/^a=candidate:[^\n]*$/gm, '');
  const wrap = (desc) => desc && { type: desc.type, sdp: strip(desc.sdp), toJSON() { return { type: desc.type, sdp: strip(desc.sdp) }; } };
  const Patched = function (config, ...rest) {
    const pc = new Orig(Object.assign({}, config, { iceServers: [] }), ...rest);
    try { Object.defineProperty(pc, 'onicecandidate', { configurable: true, enumerable: true, get: () => null, set: () => {} }); } catch (e) {}
    try {
      const add = pc.addEventListener.bind(pc);
      pc.addEventListener = function (type, ...args) {
        if (type === 'icecandidate' || type === 'icecandidateerror') return;
        return add(type, ...args);
      };
    } catch (e) {}
    for (const prop of ['localDescription', 'remoteDescription', 'pendingLocalDescription', 'pendingRemoteDescription', 'currentLocalDescription', 'currentRemoteDescription']) {
      const desc = Object.getOwnPropertyDescriptor(Orig.prototype, prop);
      if (desc && desc.get) {
        try { Object.defineProperty(pc, prop, { configurable: true, enumerable: true, get() { return wrap(desc.get.call(pc)); } }); } catch (e) {}
      }
    }
    return pc;
  };
  Patched.prototype = Orig.prototype;
  try { Object.defineProperty(window, 'RTCPeerConnection', { configurable: true, writable: true, value: Patched }); } catch (e) {}
}"#
    .to_string()
}

fn font_patch(fonts: &[String]) -> AppResult<String> {
    // Only the listed families count as installed. Font checks for any other
    // family report "missing", so detection sees exactly the allowed set.
    // The family is the first name after the CSS size, e.g. "12px Arial, sans".
    const CHECK: &str = r#"
  const origCheck = document.fonts.check.bind(document.fonts);
  document.fonts.check = (font, text) => {
    const fam = String(font)
      .replace(/^.*?\d(\.\d+)?(px|pt|em|rem|%)\s+/, '')
      .split(',')[0]
      .replace(/["']/g, '')
      .trim();
    if (fam && !ALLOWED.has(fam) && !GENERIC.has(fam)) return false;
    return origCheck(font, text);
  };
"#;
    Ok(format!(
        "const ALLOWED = new Set({});\nconst GENERIC = new Set(['serif', 'sans-serif', 'monospace', 'cursive', 'fantasy', 'system-ui']);\nif (document.fonts) {{{CHECK}}}",
        serde_json::to_string(fonts)?
    ))
}

